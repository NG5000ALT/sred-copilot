import Link from "next/link";
import type { ReactNode } from "react";

export type Status = "eligible" | "borderline" | "not_eligible" | "insufficient_evidence" | "candidate";

const STATUS: Record<Status, { label: string; cls: string }> = {
  eligible: { label: "Eligible", cls: "bg-eligible-wash text-eligible" },
  borderline: { label: "Borderline", cls: "bg-borderline-wash text-borderline" },
  not_eligible: { label: "Not eligible", cls: "bg-excluded-wash text-excluded" },
  insufficient_evidence: { label: "Too little evidence", cls: "bg-excluded-wash text-excluded" },
  candidate: { label: "Not assessed", cls: "bg-wash text-meta" },
};

export function StatusBadge({ status }: { status: Status }) {
  const s = STATUS[status] ?? STATUS.candidate;
  return <span className={`inline-block rounded px-2 py-0.5 text-sm font-medium ${s.cls}`}>{s.label}</span>;
}

/** Marks anything a model produced. */
export function DraftLabel() {
  return <span title="Generated by a model. Review before relying on it." className="rounded border border-accent/30 px-1.5 py-px text-xs font-medium text-accent">Draft</span>;
}

export function PageHeader({ title, children }: { title: string; children?: ReactNode }) {
  return (
    <header className="mb-8 flex flex-wrap items-end justify-between gap-4 border-b border-rule pb-5">
      <h1 className="font-serif text-3xl font-semibold tracking-tight">{title}</h1>
      {children}
    </header>
  );
}

export function Button({ children, variant = "primary", ...props }: React.ButtonHTMLAttributes<HTMLButtonElement> & { variant?: "primary" | "quiet" | "danger" }) {
  const cls = {
    primary: "bg-accent text-white hover:bg-accent/90",
    quiet: "border border-rule bg-paper text-ink hover:bg-wash",
    danger: "bg-fail text-white hover:bg-fail/90",
  }[variant];
  return <button {...props} className={`rounded-md px-4 py-2 text-sm font-medium disabled:opacity-50 ${cls} ${props.className ?? ""}`}>{children}</button>;
}

export function LinkButton({ href, children }: { href: string; children: ReactNode }) {
  return <Link href={href} className="inline-block rounded-md bg-accent px-4 py-2 text-sm font-medium text-white hover:bg-accent/90">{children}</Link>;
}

export function Empty({ title, children }: { title: string; children?: ReactNode }) {
  return (
    <div className="rounded-lg border border-dashed border-rule px-6 py-10 text-center">
      <p className="font-medium">{title}</p>
      {children && <div className="mt-2 text-meta">{children}</div>}
    </div>
  );
}

export function UnverifiedBadge({ verified, source }: { verified: boolean; source: string }) {
  return verified
    ? <span title={source} className="cursor-help text-xs text-eligible">verified</span>
    : <span title={source} className="cursor-help rounded bg-borderline-wash px-1.5 py-px text-xs text-borderline">unverified rate</span>;
}
